#[test]
#[ignore = "requires a DeepSeek Harness CLI"]
fn deepseek_harness_headless_attributes_file_edits() {
    let cli = std::env::var_os("GIT_AI_TEST_DEEPSEEK_HARNESS_CLI")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("dsh"));
    let workspace = tempfile::tempdir().unwrap();
    let root = workspace.path().canonicalize().unwrap();
    let repo = TestRepo::new_at_path(&root.join("repo-a"));
    let other = TestRepo::new_at_path(&root.join("repo-b"));
    let remote = "https://git.xiaojukeji.com/fixture/deepseek-harness.git";
    repo.git(&["remote", "add", "origin", remote]).unwrap();
    other.git(&["remote", "add", "origin", remote]).unwrap();
    let initial = "Replace this line.\nAnchor one.\nAnchor two.\nAnchor three.\n";
    fs::write(repo.path().join("existing.txt"), initial).unwrap();
    repo.stage_all_and_commit("Baseline A").unwrap();
    repo.filename("existing.txt").assert_committed_lines(lines![
        "Replace this line.".unattributed_human(),
        "Anchor one.".unattributed_human(),
        "Anchor two.".unattributed_human(),
        "Anchor three.".unattributed_human(),
    ]);
    fs::write(other.path().join("existing.txt"), "Before the tool runs.\n").unwrap();
    other.stage_all_and_commit("Baseline B").unwrap();
    other
        .filename("existing.txt")
        .assert_committed_lines(lines!["Before the tool runs.".unattributed_human(),]);
    fs::write(
        repo.path().join("existing.txt"),
        format!("{initial}Manual pending line.\n"),
    )
    .unwrap();

    let harness = HeadlessHarness::new(&repo, root.clone(), cli);
    let mut server = mockito::Server::new();
    let _models = mock_models(&mut server);
    let completed = Arc::new(Mutex::new(Vec::new()));
    let response_results = Arc::clone(&completed);
    let messages = server
        .mock("POST", Matcher::Regex("/messages$".into()))
        .with_header("content-type", "text/event-stream")
        .with_body_from_request(move |request| {
            scripted_tool_response(request, &response_results).into_bytes()
        })
        .expect_at_least(4)
        .create();

    let session = harness.run(&server.url(), "Apply the test changes.", None);
    messages.assert();
    assert_eq!(
        *completed.lock().unwrap(),
        ["write-file", "read-file", "edit-file"]
    );

    repo.sync_daemon();
    other.sync_daemon();
    let first = repo.stage_all_and_commit("Harness edit").unwrap();
    repo.filename("existing.txt").assert_committed_lines(lines![
        "Edited by Harness.".ai(),
        "Anchor one.".unattributed_human(),
        "Anchor two.".unattributed_human(),
        "Anchor three.".unattributed_human(),
        "Manual pending line.".unattributed_human(),
    ]);
    let second = other.stage_all_and_commit("Harness write").unwrap();
    other
        .filename("new/nested/generated.txt")
        .assert_committed_lines(lines!["Generated by Harness.".ai(),]);
    other
        .filename("existing.txt")
        .assert_committed_lines(lines!["Before the tool runs.".unattributed_human(),]);
    for commit in [first, second] {
        let sessions = commit.authorship_log.metadata.sessions;
        assert_eq!(sessions.len(), 1);
        let id = &sessions.values().next().unwrap().agent_id;
        assert_eq!(id.tool, "deepseek-harness");
        assert_eq!(id.id, session);
        assert!(id.model.starts_with("deepseek-"), "model: {}", id.model);
    }
}

struct HeadlessHarness<'a> {
    repo: &'a TestRepo,
    root: PathBuf,
    cli: PathBuf,
    overlay: PathBuf,
}

impl<'a> HeadlessHarness<'a> {
    fn new(repo: &'a TestRepo, root: PathBuf, cli: PathBuf) -> Self {
        let module = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("agent-support/deepseek-harness/index.mjs");
        let overlay = root.join("probe.yml");
        fs::write(
            &overlay,
            format!(
                "- insert:\n  - id: git-ai-deepseek-harness\n    name: {}\n",
                serde_json::to_string(module.to_str().unwrap()).unwrap()
            ),
        )
        .unwrap();

        Self {
            repo,
            root,
            cli,
            overlay,
        }
    }

    fn run(&self, url: &str, prompt: &str, session_id: Option<&str>) -> String {
        let git_ai = self.repo.git_ai_command_without_pre_sync_for_test(&[], &[]);
        let path = std::env::join_paths(
            [PathBuf::from(git_ai.get_program())
                .parent()
                .unwrap()
                .to_owned()]
            .into_iter()
            .chain(std::env::split_paths(&std::env::var_os("PATH").unwrap())),
        )
        .unwrap();
        let mut command = Command::new(&self.cli);
        command
            .args(["--profile", "headless", "--patch"])
            .arg(&self.overlay)
            .arg("--json");
        if let Some(id) = session_id {
            command.args(["--session-id", id]);
        }
        let output = command
            .arg(prompt)
            .current_dir(&self.root)
            .envs(
                git_ai
                    .get_envs()
                    .filter_map(|(key, value)| value.map(|value| (key, value))),
            )
            .env("PATH", path)
            .env("DSH_HOME", self.root.join("Harness home"))
            .env("XDG_CACHE_HOME", self.root.join("cache"))
            .env("DEEPSEEK_API_KEY", "git-ai-local-test")
            .env("DEEPSEEK_BASE_URL", url)
            // Exercise the production receipt flag. TestRepo also sets the legacy test DB variable.
            .env_remove("GIT_AI_TEST_DB_PATH")
            .stdin(Stdio::null())
            .output()
            .unwrap();
        let stdout = String::from_utf8_lossy(&output.stdout);
        let stderr = String::from_utf8_lossy(&output.stderr);
        assert!(
            output.status.success(),
            "Harness stdout:\n{stdout}\nHarness stderr:\n{stderr}"
        );
        stdout
            .lines()
            .find_map(|line| {
                let event: Value = serde_json::from_str(line).ok()?;
                (event["type"] == "final").then(|| event["sessionId"].as_str().unwrap().to_owned())
            })
            .unwrap()
    }
}

fn mock_models(server: &mut mockito::Server) -> mockito::Mock {
    server
        .mock("GET", Matcher::Regex("/models$".into()))
        .with_header("content-type", "application/json")
        .with_body(
            json!({"object": "list", "data": [{"id": "deepseek-flash", "object": "model"}]})
                .to_string(),
        )
        .create()
}

fn scripted_tool_response(request: &Request, results: &Mutex<Vec<String>>) -> String {
    let request: Value = serde_json::from_slice(request.body().unwrap()).unwrap();
    let mut observed = results.lock().unwrap();
    *observed = request["messages"]
        .as_array()
        .unwrap()
        .iter()
        .filter_map(|message| message["content"].as_array())
        .flatten()
        .filter(|item| item["type"] == "tool_result" && item["is_error"] != true)
        .map(|item| item["tool_use_id"].as_str().unwrap().to_owned())
        .collect();
    let calls = [
        (
            "write-file",
            "write",
            json!({"file_path": "repo-b/new/nested/generated.txt", "content": "Generated by Harness.\n"}),
        ),
        (
            "read-file",
            "read",
            json!({"file_path": "repo-a/existing.txt"}),
        ),
        (
            "edit-file",
            "edit",
            json!({"file_path": "repo-a/existing.txt", "old_string": "Replace this line.", "new_string": "Edited by Harness."}),
        ),
    ];

    messages_response(
        &request,
        observed.len(),
        calls.get(observed.len()),
        "I will apply the edit.",
    )
}

fn messages_response(
    request: &Value,
    step: usize,
    call: Option<&(&str, &str, Value)>,
    text: &str,
) -> String {
    let mut output = String::new();
    let mut frame = |kind: &str, mut data: Value| {
        data["type"] = json!(kind);
        write!(output, "event: {kind}\ndata: {data}\n\n").unwrap();
    };
    frame(
        "message_start",
        json!({"message": {
            "id": format!("fixture-{step}"), "type": "message", "role": "assistant",
            "content": [], "model": request["model"], "stop_reason": null, "stop_sequence": null,
            "usage": {"input_tokens": 2, "output_tokens": 0},
        }}),
    );
    frame(
        "content_block_start",
        json!({"index": 0, "content_block": {"type": "text", "text": ""}}),
    );
    frame(
        "content_block_delta",
        json!({"index": 0, "delta": {"type": "text_delta", "text": if call.is_some() { text } else { "Turn finished." }}}),
    );
    frame("content_block_stop", json!({"index": 0}));
    let reason = if let Some((id, name, args)) = call {
        frame(
            "content_block_start",
            json!({"index": 1, "content_block": {"type": "tool_use", "id": id, "name": name, "input": {}}}),
        );
        frame(
            "content_block_delta",
            json!({"index": 1, "delta": {"type": "input_json_delta", "partial_json": args.to_string()}}),
        );
        frame("content_block_stop", json!({"index": 1}));
        "tool_use"
    } else {
        "end_turn"
    };
    frame(
        "message_delta",
        json!({"delta": {"stop_reason": reason, "stop_sequence": null}, "usage": {"output_tokens": 8}}),
    );
    frame("message_stop", json!({}));
    output
}

#[test]
#[ignore = "requires a DeepSeek Harness CLI"]
fn deepseek_harness_resumed_transcript_links_two_commits() {
    use git_ai::authorship::authorship_log_serialization::AuthorshipLog;

    let cli = std::env::var_os("GIT_AI_TEST_DEEPSEEK_HARNESS_CLI")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("dsh"));
    let workspace = tempfile::tempdir().unwrap();
    let root = workspace.path().canonicalize().unwrap();
    let repo = TestRepo::new_at_path(&root.join("project"));
    repo.git(&[
        "remote",
        "add",
        "origin",
        "https://git.xiaojukeji.com/fixture/deepseek-harness.git",
    ])
    .unwrap();
    let harness = HeadlessHarness::new(&repo, root.clone(), cli);
    let mut server = mockito::Server::new();
    let _models = mock_models(&mut server);
    let first_prompt = "Write the first marker to linked.txt.";
    let second_prompt = "Replace the first marker with the second marker.";
    let first_reply = "I will write the first marker.";
    let second_reply = "I will replace the marker now.";
    let tool_result_marker = "VISIBLE_ONLY_IN_READ_RESULT_7815";
    let human_line = "Preserve this manual line.";
    fs::write(root.join("context.txt"), tool_result_marker).unwrap();
    fs::write(
        repo.path().join("linked.txt"),
        format!("Original marker.\n{human_line}\n"),
    )
    .unwrap();
    repo.stage_all_and_commit("Seed tracked file").unwrap();
    repo.filename("linked.txt").assert_committed_lines(lines![
        "Original marker.".unattributed_human(),
        human_line.unattributed_human(),
    ]);

    let captured_result = Arc::new(Mutex::new(false));
    let saw_result = Arc::clone(&captured_result);
    let messages = server.mock("POST", Matcher::Regex("/messages$".into()))
        .with_header("content-type", "text/event-stream")
        .with_body_from_request(move |request| {
            let request: Value = serde_json::from_slice(request.body().unwrap()).unwrap();
            let blocks = request["messages"].as_array().unwrap().iter()
                .filter_map(|message| message["content"].as_array()).flatten().collect::<Vec<_>>();
            let completed = |id: &str| blocks.iter().any(|block| {
                block["type"] == "tool_result" && block["tool_use_id"] == id && block["is_error"] != true
            });
            let turn_two = blocks.iter().any(|block| block["text"] == second_prompt);
            if blocks.iter().any(|block| block["type"] == "tool_result" && block["tool_use_id"] == "read-context" && block.to_string().contains(tool_result_marker)) {
                *saw_result.lock().unwrap() = true;
            }
            let path = "project/linked.txt";
            let (step, call, text) = if !turn_two && !completed("read-first") {
                (0, Some(("read-first", "read", json!({"file_path": path}))), "I will read the file.")
            } else if !turn_two && !completed("write-first") {
                (1, Some(("write-first", "write", json!({"file_path": path, "content": format!("First marker.\n{human_line}\n")}))), first_reply)
            } else if turn_two && !completed("read-second") {
                (3, Some(("read-second", "read", json!({"file_path": path}))), "I will read the first version.")
            } else if turn_two && !completed("read-context") {
                (4, Some(("read-context", "read", json!({"file_path": "context.txt"}))), "I will read the context.")
            } else if turn_two && !completed("edit-second") {
                (5, Some(("edit-second", "edit", json!({"file_path": path, "old_string": "First marker.", "new_string": "Second marker."}))), second_reply)
            } else {
                (if turn_two { 6 } else { 2 }, None, "")
            };
            messages_response(&request, step, call.as_ref(), text).into_bytes()
        }).expect_at_least(7).create();

    let session = harness.run(&server.url(), first_prompt, None);
    repo.sync_daemon();
    let first_sha = repo
        .stage_all_and_commit("First Harness turn")
        .unwrap()
        .commit_sha;
    repo.filename("linked.txt").assert_committed_lines(lines![
        "First marker.".ai(),
        human_line.unattributed_human(),
    ]);

    assert_eq!(
        harness.run(&server.url(), second_prompt, Some(&session)),
        session
    );
    repo.sync_daemon();
    let second_sha = repo
        .stage_all_and_commit("Second Harness turn")
        .unwrap()
        .commit_sha;
    repo.filename("linked.txt").assert_committed_lines(lines![
        "Second marker.".ai(),
        human_line.unattributed_human(),
    ]);
    messages.assert();
    assert!(
        *captured_result.lock().unwrap(),
        "fixture must deliver the read result to Harness"
    );

    let lookup = |sha: &str| {
        let note = repo.read_authorship_note(sha).expect("persisted Git note");
        let note = AuthorshipLog::deserialize_from_string(&note).unwrap();
        let trace = note
            .attestations
            .iter()
            .find(|file| file.file_path == "linked.txt")
            .unwrap()
            .entries
            .iter()
            .find(|entry| entry.hash.starts_with("s_"))
            .unwrap()
            .hash
            .clone();
        let (key, _) = trace
            .split_once("::")
            .expect("AI line has checkpoint-specific attestation");
        assert_eq!(note.metadata.sessions[key].agent_id.id, session);
        let shown = repo.git_ai(&["show", sha]).unwrap();
        assert!(shown.contains(&trace));
        let output = repo
            .git_ai(&["show-prompt", &trace, "--commit", sha])
            .unwrap();
        let value: Value = serde_json::from_str(&output).unwrap();
        assert_eq!(value["commit"], sha);
        assert_eq!(value["prompt_id"], trace);
        assert_eq!(value["prompt"]["agent_id"]["id"], session);
        assert_eq!(value["prompt"]["agent_id"]["tool"], "deepseek-harness");
        assert_eq!(value["prompt"]["agent_id"]["model"], "deepseek-flash");
        let history_output = repo.git_ai(&["show-prompt", &trace]).unwrap();
        assert_eq!(
            serde_json::from_str::<Value>(&history_output).unwrap(),
            value
        );
        let messages = value["transcript"]["messages"]
            .as_array()
            .unwrap_or_else(|| panic!("commit {sha} did not return transcript: {value}"))
            .clone();
        (trace, messages)
    };
    let (first_trace, first) = lookup(&first_sha);
    let (second_trace, second) = lookup(&second_sha);
    assert_ne!(first_trace, second_trace);
    assert_eq!(
        first_trace.split("::").next(),
        second_trace.split("::").next()
    );
    assert!(second.starts_with(&first));
    let texts = |messages: &[Value], kind: &str| {
        messages
            .iter()
            .filter(|entry| entry["type"] == kind)
            .map(|entry| entry["text"].as_str().unwrap().to_owned())
            .collect::<Vec<_>>()
    };
    let tools = |messages: &[Value]| {
        messages
            .iter()
            .filter(|entry| entry["type"] == "tool_use")
            .map(|entry| entry["name"].as_str().unwrap().to_owned())
            .collect::<Vec<_>>()
    };
    assert_eq!(texts(&first, "user"), [first_prompt]);
    assert_eq!(texts(&second, "user"), [first_prompt, second_prompt]);
    assert!(texts(&first, "assistant").contains(&first_reply.to_owned()));
    assert!(texts(&second, "assistant").contains(&second_reply.to_owned()));
    assert_eq!(tools(&first), ["read", "write"]);
    assert_eq!(tools(&second), ["read", "write", "read", "read", "edit"]);
    assert!(second.iter().all(|entry| matches!(
        entry["type"].as_str(),
        Some("user" | "assistant" | "tool_use")
    )));
    assert!(
        second
            .iter()
            .all(|entry| !entry.to_string().contains(tool_result_marker))
    );
    assert!(
        repo.git_ai(&["show-prompt", &second_trace, "--commit", &first_sha])
            .is_err()
    );
    println!("Harness session {session}");
    println!("First commit {first_sha} {first_trace}");
    println!("Second commit {second_sha} {second_trace}");
}
